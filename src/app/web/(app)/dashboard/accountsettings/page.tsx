"use client";
import Link from "next/link";
import { fmtDate, inr, useCollection, useMe, type Row } from "@/lib/client";
import { Btn, DataTable, EmptySearch, Panel, Pill, Title, type Col } from "@/components/dash/kit";
import { Icon } from "@/components/dash/icons";
import { COMMISSION, PLAN_LABEL, dash } from "@/components/dash/nav";

const PLAN_INFO = {
  basic: { title: "Basic - Zero Fixed Fee", convenience: "2%", intl: "5% / 5%", blurb: "Unlimited services, unlimited landing pages, unlimited users, 10 free email credits per user, 20 GB Media Upload and more!" },
  pro: { title: "Pro - ₹5,000/month", convenience: "2%", intl: "5% / 5%", blurb: "Unlimited students & storage, refund automation, 50k emails/month, exclusive templates and more." },
  advanced: { title: "Advanced - ₹15,000/month", convenience: "1.5%", intl: "5% / 5%", blurb: "Community channels & forums, affiliates, gamification, DRM course protection and more." },
  ultimate: { title: "Ultimate - ₹35,000/month", convenience: "1.9%", intl: "5% / 5%", blurb: "AI-Verse stack, customer success manager, instant withdrawal, no-cost EMI and more." },
};

function invoicePdf(r: Row, name: string) {
  const w = window.open("", "_blank", "width=720,height=900");
  if (!w) return;
  const gst = Math.round(Number(r.amount) - Number(r.amount) / 1.18);
  w.document.write(`<html><head><title>${r.number}</title><style>body{font-family:Poppins,system-ui;padding:40px;color:#0f0f0f}h1{color:#f2962c}table{width:100%;border-collapse:collapse;margin-top:24px}td,th{border-bottom:1px solid #eee;padding:10px;text-align:left}</style></head><body><h1>tagmango</h1><p><b>Tax invoice</b> ${r.number}<br/>Date: ${new Date(String(r.createdAt)).toLocaleDateString("en-IN")}<br/>Billed to: ${name}</p><table><tr><th>Item</th><th>Amount</th></tr><tr><td>${r.product}</td><td>₹${(Number(r.amount) - gst).toLocaleString("en-IN")}</td></tr><tr><td>GST (18%)</td><td>₹${gst.toLocaleString("en-IN")}</td></tr><tr><th>Total</th><th>₹${Number(r.amount).toLocaleString("en-IN")}</th></tr></table><p style="margin-top:24px;color:#888">Test-mode invoice generated by the TagMango clone.</p><script>window.print()</script></body></html>`);
  w.document.close();
}

export default function Billing() {
  const { me } = useMe();
  const inv = useCollection("invoices");
  const info = PLAN_INFO[me.plan];
  const cols: Col<Row>[] = [
    { key: "n", label: "Invoice No.", render: (r) => String(r.number) },
    { key: "d", label: "Billing Date", render: (r) => fmtDate(r.createdAt) },
    { key: "s", label: "Status", render: (r) => <Pill>{String(r.status)}</Pill> },
    { key: "p", label: "Product/Plan", render: (r) => String(r.product) },
    { key: "a", label: "Amount", render: (r) => inr(Number(r.amount)) },
    { key: "x", label: "Action", render: (r) => <Btn variant="outline" className="h-8 px-3 text-[13px]" icon="download" onClick={() => invoicePdf(r, me.name)}>Download</Btn> },
  ];
  return (
    <>
      <Panel className="p-5">
        <Title right={<Link href={dash("plans")}><Btn>Change plan</Btn></Link>}>Billing</Title>
        <div className="mt-4 rounded-[10px] border border-[#ededed] p-5">
          <p className="text-[11px] font-semibold uppercase tracking-wider text-[#6b6b7b]">Current plan</p>
          <p className="mt-2 flex items-center gap-2 text-[22px] font-semibold"><Icon name="billing" className="h-6 w-6 text-[#c7740f]" />{info.title}</p>
          <div className="mt-4 max-w-md rounded-md bg-[#f7f7f8] p-4 text-[14px]">
            <p className="mb-2 font-semibold">Transaction Charges</p>
            {[["Commission", `${Math.round(COMMISSION[me.plan] * 1000) / 10}%`], ["Convenience Fee", info.convenience], ["International PG (Onetime / Subscription)", info.intl]].map(([k, v]) => <div key={k} className="flex justify-between py-1"><span className="text-[#4a4a59]">{k}</span><b>{v}</b></div>)}
          </div>
          <p className="mt-3 text-[13px] text-[#4a4a59]">{info.blurb}</p>
          {me.whiteLabel && <p className="mt-2"><Pill tone="blue">Freedom Setup active</Pill></p>}
        </div>
      </Panel>
      <Panel className="mt-5 p-5" delay={0.06}>
        <Title sub={`Plan: ${PLAN_LABEL[me.plan]}`}>Invoices</Title>
        <div className="mt-3"><DataTable cols={cols} rows={inv.rows} loading={inv.loading} empty={<EmptySearch title="No invoices found!" />} /></div>
      </Panel>
    </>
  );
}
